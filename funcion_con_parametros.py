# Función 1: Saludar
def saludar(nombre):
    print("Hola", nombre)


# Función 2: Sumar dos números
def sumar(a, b):
    resultado = a + b
    print("La suma es:", resultado)


# Función 3: Calcular el área de un rectángulo
def area_rectangulo(base, altura):
    area = base * altura
    print("El área del rectángulo es:", area)


# Llamar a las funciones
saludar("Frida")

sumar(10, 5)

area_rectangulo(8, 4)